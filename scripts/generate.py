"""Generate ``src/zebracat/_generated/`` from ``openapi/openapi.json``.

    python scripts/generate.py            # write the files
    python scripts/generate.py --check    # exit 1 when the committed files are out of date (CI)

Standard library only. Emits:

- ``types.py``: one ``TypedDict`` per component schema (``total=False``; the docstring names the required keys),
  ``Literal`` aliases for enums. Answers stay plain dicts, so a field the server adds later never breaks a caller.
- ``operations.py``: one method per ``operationId`` on ``GeneratedOperations``. Path parameters are positional,
  query parameters and body fields are keyword-only. Every call goes through ``self._request`` (hand-written in
  ``zebracat._client``), which adds auth, retries, the idempotency key and typed errors.

The spec is produced by the backend (``manage.py spectacular --format openapi-json``); see the README.
"""

from __future__ import annotations

import argparse
import json
import keyword
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "openapi.json"
OUT = ROOT / "src" / "zebracat" / "_generated"

METHODS = ("get", "post", "put", "patch", "delete")

#: POSTs that spend money without a 402 in their answers (a card charge). Every POST that can answer 402
#: (insufficient funds) is paid as well; both get an ``Idempotency-Key``.
EXTRA_PAID = {"purchase_credits"}

#: Paid POSTs whose server replays the first answer for a repeated ``Idempotency-Key`` (24 h), so retrying one after
#: a 5xx or a dropped connection cannot start or charge a second job. Every other POST is retried on 429 only.
#: Source: backend ``public_apis/v2/lifecycle.py`` (create, clone, translate) and
#: ``public_apis/video_generation_views/*`` (the v1 creators), which call ``public_apis.idempotency``.
REPLAYS_IDEMPOTENCY_KEY = {
    "create_video",
    "clone_video",
    "translate_video",
    "idea_to_video",
    "script_to_video",
    "blog_to_video",
    "audio_to_video",
    "agentic_video",
}

HEADER = "# Generated by scripts/generate.py from openapi/openapi.json. Do not edit by hand.\n"


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def py_name(name: str) -> str:
    """A safe Python identifier for an API field name."""
    out = "".join(c if c.isalnum() or c == "_" else "_" for c in name)
    if not out or out[0].isdigit():
        out = "_" + out
    if keyword.iskeyword(out) or out in ("self", "body", "extra_body", "request_options", "idempotency_key"):
        out += "_"
    return out


def literal(values) -> str:
    return "Literal[" + ", ".join(json.dumps(v) if v is not None else "None" for v in values) + "]"


def union(types: list[str]) -> str:
    seen = []
    for t in types:
        if t not in seen:
            seen.append(t)
    has_none = "None" in seen
    rest = [t for t in seen if t != "None"]
    if not rest:
        return "None"
    core = rest[0] if len(rest) == 1 else "Union[" + ", ".join(rest) + "]"
    return f"Optional[{core}]" if has_none else core


#: Quote component references (forward references evaluated at import time, in ``types.py`` aliases). Annotations
#: under ``from __future__ import annotations`` need no quotes.
QUOTE_REFS = {"on": False}


def type_of(schema: dict | None) -> str:
    """A Python type expression for ``schema``."""
    if not schema:
        return "Any"
    if "$ref" in schema:
        name = ref_name(schema["$ref"])
        return json.dumps(name) if QUOTE_REFS["on"] else name
    if "const" in schema:
        return literal([schema["const"]])
    if "enum" in schema:
        values = [v for v in schema["enum"]]
        if all(isinstance(v, (str, int, bool)) or v is None for v in values) and values:
            lit = literal([v for v in values if v is not None])
            return f"Optional[{lit}]" if None in values else lit
    for key in ("oneOf", "anyOf"):
        if key in schema:
            return union([type_of(s) for s in schema[key]])
    if "allOf" in schema:
        parts = schema["allOf"]
        return type_of(parts[0]) if len(parts) == 1 else "Dict[str, Any]"
    t = schema.get("type")
    if isinstance(t, list):
        return union([type_of({**schema, "type": x}) for x in t])
    if t == "null":
        return "None"
    if t == "string":
        return "FileContent" if schema.get("format") == "binary" else "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "array":
        return f"List[{type_of(schema.get('items'))}]"
    if t == "object" or "properties" in schema or "additionalProperties" in schema:
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra and not schema.get("properties"):
            return f"Dict[str, {type_of(extra)}]"
        return "Dict[str, Any]"
    return "Any"


def doc_lines(text: str, indent: str) -> list[str]:
    text = (text or "").replace('"""', "'''").replace("\\", "\\\\").strip()
    return [(indent + line).rstrip() for line in text.splitlines()]


def gen_types(spec: dict) -> str:
    schemas = spec.get("components", {}).get("schemas", {})
    out = [
        HEADER,
        "from __future__ import annotations\n",
        "from typing import IO, Any, Dict, List, Literal, Optional, Tuple, TypedDict, Union\n",
        "#: A file to upload: bytes, an open binary file, or ``(filename, content[, content_type])``.",
        "FileContent = Union[bytes, IO[bytes], Tuple[str, Any], Tuple[str, Any, str]]\n",
    ]
    names = []
    for name, schema in schemas.items():
        names.append(name)
        props = schema.get("properties")
        if schema.get("type") == "object" or props is not None:
            props = props or {}
            required = schema.get("required", [])
            valid = all(k.isidentifier() and not keyword.iskeyword(k) for k in props)
            desc = schema.get("description", "")
            note = f"Required keys: {', '.join(required)}." if required else ""
            if valid and props:
                out.append(f"\nclass {name}(TypedDict, total=False):")
                body = doc_lines("\n\n".join(x for x in (desc, note) if x), "    ")
                if body:
                    out.append('    """' + body[0].lstrip())
                    out.extend(body[1:])
                    out.append('    """\n')
                for key, sub in props.items():
                    sub_doc = (sub.get("description") or "").strip().splitlines()
                    out.append(f"    {key}: {type_of(sub)}")
                    if sub_doc:
                        out.append(f"    #: {sub_doc[0][:110]}")
            else:
                QUOTE_REFS["on"] = True
                fields = ", ".join(f"{json.dumps(k)}: {type_of(v)}" for k, v in props.items())
                QUOTE_REFS["on"] = False
                out.append(f"\n{name} = TypedDict({json.dumps(name)}, {{{fields}}}, total=False)")
        else:
            QUOTE_REFS["on"] = True
            out.append(f"\n{name} = {type_of(schema)}")
            QUOTE_REFS["on"] = False
    out.append("\n__all__ = " + json.dumps(["FileContent"] + names, indent=4) + "\n")
    return "\n".join(out) + "\n"


def resolve(spec: dict, schema: dict) -> dict:
    while "$ref" in schema:
        schema = spec["components"]["schemas"][ref_name(schema["$ref"])]
    return schema


def body_info(spec: dict, op: dict):
    """(kind, schema, required) of the request body; kind is ``json``, ``multipart`` or None."""
    rb = op.get("requestBody")
    if not rb:
        return None, None, False
    content = rb["content"]
    first = next(iter(content))
    schema = content[first].get("schema", {})
    props = resolve(spec, schema).get("properties", {})
    has_file = any(resolve(spec, p).get("format") == "binary" for p in props.values())
    if first == "multipart/form-data" and (has_file or "application/json" not in content):
        return "multipart", schema, bool(rb.get("required"))
    if "application/json" in content:
        return "json", content["application/json"].get("schema", {}), bool(rb.get("required"))
    return "multipart", schema, bool(rb.get("required"))


def response_type(op: dict) -> str:
    """The union of the 2xx JSON answers; ``str`` (the ``Location``) for a redirect; else ``None``."""
    found = []
    for code, resp in op.get("responses", {}).items():
        if code.startswith("2") and "application/json" in (resp.get("content") or {}):
            found.append(type_of(resp["content"]["application/json"].get("schema")))
    if found:
        return union(found)
    codes = [c for c in op.get("responses", {}) if c.startswith("3")]
    if codes:
        return "str"
    return "None"


def gen_operations(spec: dict) -> tuple[str, list[str]]:
    lines = [
        HEADER,
        "from __future__ import annotations\n",
        "import warnings",
        "from typing import Any, Dict, List, Literal, Optional, Union\n",
        "from .._types import NOT_GIVEN, NotGiven, Operation, RequestOptions",
        "from .types import *  # noqa: F401,F403",
        "from .types import FileContent\n",
        "",
        "class GeneratedOperations:",
        '    """One method per operation of the Zebracat public API (operationId = method name)."""\n',
        "    def _request(self, op: Operation, *, path: Dict[str, Any], query: Dict[str, Any], body: Any,",
        "                 idempotency_key: Optional[str], request_options: Optional[RequestOptions]) -> Any:",
        "        raise NotImplementedError\n",
    ]
    table = []
    op_ids = []
    for path, item in spec["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            op_id = op["operationId"]
            op_ids.append(op_id)
            kind, schema, body_required = body_info(spec, op)
            paid = method == "post" and ("402" in op.get("responses", {}) or op_id in EXTRA_PAID)
            replays = op_id in REPLAYS_IDEMPOTENCY_KEY
            deprecated = bool(op.get("deprecated"))
            table.append(
                f"    {json.dumps(op_id)}: Operation({json.dumps(op_id)}, {json.dumps(method.upper())}, "
                f"{json.dumps(path)}, body={json.dumps(kind) if kind else None}, paid={paid}, "
                f"replays_idempotency_key={replays}, deprecated={deprecated}),"
            )
            params = item.get("parameters", []) + op.get("parameters", [])
            path_params = [p for p in params if p["in"] == "path"]
            query_params = [p for p in params if p["in"] == "query"]
            used = {py_name(p["name"]) for p in path_params + query_params}
            props, required = {}, []
            if kind:
                resolved = resolve(spec, schema or {})
                props = resolved.get("properties", {})
                required = resolved.get("required", [])
            spread = bool(props) and not any(py_name(k) in used for k in props)

            sig = ["self"]
            for p in path_params:
                sig.append(f"{py_name(p['name'])}: {type_of(p.get('schema'))}")
            sig.append("*")
            kw_required, kw_optional = [], []
            if spread:
                for key, sub in props.items():
                    readonly = resolve(spec, sub).get("readOnly") or sub.get("readOnly")
                    if readonly:
                        continue
                    t = type_of(sub)
                    if key in required and body_required:
                        kw_required.append(f"{py_name(key)}: {t}")
                    else:
                        kw_optional.append(f"{py_name(key)}: Union[{t}, NotGiven] = NOT_GIVEN")
            elif kind:
                t = type_of(schema)
                if body_required:
                    kw_required.append(f"body: {t}")
                else:
                    kw_optional.append(f"body: Union[{t}, NotGiven] = NOT_GIVEN")
            for p in query_params:
                t = type_of(p.get("schema"))
                if p.get("required"):
                    kw_required.append(f"{py_name(p['name'])}: {t}")
                else:
                    kw_optional.append(f"{py_name(p['name'])}: Union[{t}, NotGiven] = NOT_GIVEN")
            sig += kw_required + kw_optional
            if spread:
                sig.append("extra_body: Optional[Dict[str, Any]] = None")
            if paid:
                sig.append("idempotency_key: Optional[str] = None")
            sig.append("request_options: Optional[RequestOptions] = None")

            lines.append(f"    def {op_id}(")
            for s in sig:
                lines.append(f"        {s},")
            lines.append(f"    ) -> {response_type(op)}:")
            doc = [op.get("summary", "").strip(), op.get("description", "").strip()]
            doc.append(f"``{method.upper()} {path}``")
            if paid:
                doc.append(
                    "Paid: an ``Idempotency-Key`` is sent (yours, or a new one reused across this call's retries)."
                )
            if deprecated:
                doc.append(".. deprecated:: The API marks this operation deprecated.")
            body_doc = doc_lines("\n\n".join(x for x in doc if x), "        ")
            lines.append('        """' + body_doc[0].lstrip())
            lines.extend(body_doc[1:])
            lines.append('        """')
            if deprecated:
                lines.append(
                    f"        warnings.warn({json.dumps(op_id + ' is deprecated by the API.')}, "
                    "DeprecationWarning, stacklevel=2)"
                )
            path_map = ", ".join(f"{json.dumps(p['name'])}: {py_name(p['name'])}" for p in path_params)
            query_map = ", ".join(f"{json.dumps(p['name'])}: {py_name(p['name'])}" for p in query_params)
            if spread:
                body_map = ", ".join(
                    f"{json.dumps(k)}: {py_name(k)}"
                    for k, sub in props.items()
                    if not (resolve(spec, sub).get("readOnly") or sub.get("readOnly"))
                )
                lines.append(f"        body = {{{body_map}}}")
                lines.append("        if extra_body:")
                lines.append("            body.update(extra_body)")
                body_expr = "body"
            elif kind:
                body_expr = "body"
            else:
                body_expr = "None"
            lines.append("        return self._request(")
            lines.append(f"            OPERATIONS[{json.dumps(op_id)}],")
            lines.append(f"            path={{{path_map}}},")
            lines.append(f"            query={{{query_map}}},")
            lines.append(f"            body={body_expr},")
            lines.append(f"            idempotency_key={'idempotency_key' if paid else 'None'},")
            lines.append("            request_options=request_options,")
            lines.append("        )\n")
    out = "\n".join(lines)
    out += "\n\n#: Every operation of the API, by operationId.\nOPERATIONS: Dict[str, Operation] = {\n"
    out += "\n".join(table) + "\n}\n"
    return out, op_ids


def render(spec: dict) -> dict[str, str]:
    ops, op_ids = gen_operations(spec)
    info = spec.get("info", {})
    meta = (
        HEADER
        + f"\nSPEC_TITLE = {json.dumps(info.get('title', ''))}\nSPEC_VERSION = {json.dumps(info.get('version', ''))}\n"
        + f"OPERATION_IDS = {json.dumps(sorted(op_ids), indent=4)}\n"
    )
    return {
        "__init__.py": HEADER + "\nfrom .operations import OPERATIONS, GeneratedOperations\n\n"
        '__all__ = ["OPERATIONS", "GeneratedOperations"]\n',
        "types.py": gen_types(spec),
        "operations.py": ops,
        "meta.py": meta,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail when the generated files are out of date")
    args = parser.parse_args()
    spec = json.loads(SPEC.read_text())
    files = render(spec)
    stale = []
    for name, text in files.items():
        target = OUT / name
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
    if stale:
        print("out of date: " + ", ".join(stale) + " (run python scripts/generate.py)", file=sys.stderr)
        return 1
    if not args.check:
        print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
